package it.pta.render;

/** All GLSL ES 2.0 shaders used by the renderer, kept in one auditable place. */
public final class Shaders {

    public static final String WORLD_VERT =
            "attribute vec3 a_position;\n"
            + "attribute vec3 a_normal;\n"
            + "attribute vec4 a_color;\n"
            + "attribute vec2 a_texCoord0;\n"
            + "uniform mat4 u_projView;\n"
            + "uniform mat4 u_model;\n"
            + "varying vec4 v_color;\n"
            + "varying vec3 v_normal;\n"
            + "varying vec2 v_uv;\n"
            + "varying vec3 v_world;\n"
            + "void main() {\n"
            + "  vec4 wp = u_model * vec4(a_position, 1.0);\n"
            + "  v_world = wp.xyz;\n"
            + "  v_normal = normalize((u_model * vec4(a_normal, 0.0)).xyz);\n"
            + "  v_color = a_color;\n"
            + "  v_uv = a_texCoord0;\n"
            + "  gl_Position = u_projView * wp;\n"
            + "}\n";

    public static final String WORLD_FRAG =
            "#ifdef GL_ES\nprecision mediump float;\n#endif\n"
            + "uniform sampler2D u_tex;\n"
            + "uniform vec3 u_camPos;\n"
            + "uniform vec3 u_sunDir;\n"
            + "uniform vec3 u_sunColor;\n"
            + "uniform vec3 u_ambient;\n"
            + "uniform vec3 u_fogColor;\n"
            + "uniform float u_fogStart;\n"
            + "uniform float u_fogEnd;\n"
            + "uniform float u_night;\n"
            + "uniform vec4 u_tint;\n"
            + "varying vec4 v_color;\n"
            + "varying vec3 v_normal;\n"
            + "varying vec2 v_uv;\n"
            + "varying vec3 v_world;\n"
            + "void main() {\n"
            + "  float tile = floor(v_color.a + 0.5);\n"
            + "  float col = mod(tile, 3.0);\n"
            + "  float row = floor(tile / 3.0);\n"
            + "  vec2 uv = fract(v_uv);\n"
            + "  uv = clamp(uv, 0.012, 0.988);\n"
            + "  vec2 auv = vec2((col + uv.x) / 3.0, (2.0 - row + uv.y) / 3.0);\n"
            + "  vec4 tex = texture2D(u_tex, auv);\n"
            + "  vec3 base = tex.rgb * v_color.rgb * u_tint.rgb;\n"
            + "  vec3 n = normalize(v_normal);\n"
            + "  float ndl = max(dot(n, u_sunDir), 0.0);\n"
            + "  float hemi = 0.58 + 0.42 * max(n.y, 0.0);\n"
            + "  vec3 lit = base * (u_ambient * hemi + u_sunColor * ndl);\n"
            + "  vec3 viewDir = normalize(u_camPos - v_world);\n"
            + "  vec3 hv = normalize(u_sunDir + viewDir);\n"
            + "  float spec = pow(max(dot(n, hv), 0.0), 40.0) * 0.14;\n"
            + "  lit += u_sunColor * spec;\n"
            + "  lit += base * tex.a * u_night * vec3(1.15, 0.92, 0.62);\n"
            + "  float d = length(u_camPos - v_world);\n"
            + "  float fog = clamp((d - u_fogStart) / max(1.0, u_fogEnd - u_fogStart), 0.0, 1.0);\n"
            + "  gl_FragColor = vec4(mix(lit, u_fogColor, fog), 1.0);\n"
            + "}\n";

    public static final String SKY_VERT =
            "attribute vec2 a_position;\n"
            + "uniform mat4 u_invProjView;\n"
            + "uniform vec3 u_camPos;\n"
            + "varying vec3 v_dir;\n"
            + "void main() {\n"
            + "  vec4 far = u_invProjView * vec4(a_position, 0.9999, 1.0);\n"
            + "  v_dir = normalize(far.xyz / far.w - u_camPos);\n"
            + "  gl_Position = vec4(a_position, 1.0, 1.0);\n"
            + "}\n";

    public static final String SKY_FRAG =
            "#ifdef GL_ES\nprecision mediump float;\n#endif\n"
            + "uniform vec3 u_zenith;\n"
            + "uniform vec3 u_horizon;\n"
            + "uniform vec3 u_fogColor;\n"
            + "uniform vec3 u_sunDir;\n"
            + "uniform vec3 u_sunColor;\n"
            + "uniform float u_night;\n"
            + "uniform float u_time;\n"
            + "uniform float u_cloud;\n"
            + "varying vec3 v_dir;\n"
            + "float hash(vec2 p) { return fract(sin(dot(p, vec2(127.1, 311.7))) * 43758.5453); }\n"
            + "float noise(vec2 p) {\n"
            + "  vec2 i = floor(p); vec2 f = fract(p);\n"
            + "  f = f * f * (3.0 - 2.0 * f);\n"
            + "  float a = hash(i); float b = hash(i + vec2(1.0, 0.0));\n"
            + "  float c = hash(i + vec2(0.0, 1.0)); float d = hash(i + vec2(1.0, 1.0));\n"
            + "  return mix(mix(a, b, f.x), mix(c, d, f.x), f.y);\n"
            + "}\n"
            + "float fbm(vec2 p) {\n"
            + "  float v = 0.0; float a = 0.5;\n"
            + "  for (int i = 0; i < 4; i++) { v += a * noise(p); p *= 2.03; a *= 0.5; }\n"
            + "  return v;\n"
            + "}\n"
            + "void main() {\n"
            + "  vec3 dir = normalize(v_dir);\n"
            + "  float up = max(dir.y, 0.0);\n"
            + "  vec3 col = mix(u_horizon, u_zenith, pow(up, 0.55));\n"
            + "  float sunDot = max(dot(dir, u_sunDir), 0.0);\n"
            + "  col += u_sunColor * pow(sunDot, 6.0) * 0.22;\n"
            + "  col += u_sunColor * pow(sunDot, 900.0) * 2.4;\n"
            + "  if (dir.y > 0.015) {\n"
            + "    vec2 cuv = dir.xz / (dir.y + 0.18) * 1.35 + vec2(u_time * 0.004, u_time * 0.0022);\n"
            + "    float c = fbm(cuv * 1.7);\n"
            + "    float cover = smoothstep(0.52 - u_cloud * 0.35, 0.92, c);\n"
            + "    float fade = smoothstep(0.015, 0.22, dir.y);\n"
            + "    vec3 cloudCol = mix(vec3(1.0, 0.99, 0.96), vec3(0.35, 0.38, 0.45), u_night * 0.85);\n"
            + "    cloudCol = mix(cloudCol, u_sunColor * 0.9 + 0.25, 0.25 * (1.0 - u_night));\n"
            + "    col = mix(col, cloudCol, cover * fade * 0.85);\n"
            + "  }\n"
            + "  if (u_night > 0.15) {\n"
            + "    vec2 sp = floor(dir.xz * 420.0 / max(0.25, dir.y + 0.6));\n"
            + "    float s = hash(sp);\n"
            + "    float star = smoothstep(0.9975, 1.0, s) * u_night * smoothstep(0.05, 0.3, dir.y);\n"
            + "    col += vec3(star) * (0.7 + 0.3 * sin(u_time * 3.0 + s * 40.0));\n"
            + "    float moonDot = max(dot(dir, -u_sunDir), 0.0);\n"
            + "    col += vec3(0.85, 0.88, 0.95) * pow(moonDot, 2400.0) * u_night * 1.6;\n"
            + "  }\n"
            + "  float horizonFade = 1.0 - smoothstep(0.0, 0.06, abs(dir.y));\n"
            + "  col = mix(col, u_fogColor, horizonFade * 0.75);\n"
            + "  gl_FragColor = vec4(col, 1.0);\n"
            + "}\n";

    public static final String POST_VERT =
            "attribute vec2 a_position;\n"
            + "varying vec2 v_uv;\n"
            + "void main() { v_uv = a_position * 0.5 + 0.5; gl_Position = vec4(a_position, 0.0, 1.0); }\n";

    public static final String POST_FRAG =
            "#ifdef GL_ES\nprecision mediump float;\n#endif\n"
            + "uniform sampler2D u_tex;\n"
            + "uniform vec2 u_texel;\n"
            + "uniform float u_aa;\n"
            + "uniform float u_vignette;\n"
            + "uniform float u_saturation;\n"
            + "uniform float u_rain;\n"
            + "uniform float u_time;\n"
            + "varying vec2 v_uv;\n"
            + "void main() {\n"
            + "  vec3 c = texture2D(u_tex, v_uv).rgb;\n"
            + "  if (u_aa > 0.5) {\n"
            + "    vec3 n = texture2D(u_tex, v_uv + vec2(0.0, u_texel.y)).rgb;\n"
            + "    vec3 s = texture2D(u_tex, v_uv - vec2(0.0, u_texel.y)).rgb;\n"
            + "    vec3 e = texture2D(u_tex, v_uv + vec2(u_texel.x, 0.0)).rgb;\n"
            + "    vec3 w = texture2D(u_tex, v_uv - vec2(u_texel.x, 0.0)).rgb;\n"
            + "    c = (c * 2.0 + n + s + e + w) / 6.0;\n"
            + "  }\n"
            + "  float l = dot(c, vec3(0.299, 0.587, 0.114));\n"
            + "  c = mix(vec3(l), c, u_saturation);\n"
            + "  vec2 d = v_uv - vec2(0.5);\n"
            + "  float vig = 1.0 - u_vignette * dot(d, d) * 1.15;\n"
            + "  c *= vig;\n"
            + "  if (u_rain > 0.01) {\n"
            + "    float streak = fract(v_uv.y * 46.0 + u_time * 1.7 + sin(v_uv.x * 60.0) * 0.25);\n"
            + "    float line = smoothstep(0.965, 1.0, streak) * u_rain * 0.20;\n"
            + "    c += vec3(line);\n"
            + "    c = mix(c, c * vec3(0.82, 0.86, 0.94), u_rain * 0.5);\n"
            + "  }\n"
            + "  gl_FragColor = vec4(c, 1.0);\n"
            + "}\n";

    /** Additive billboard glow (lamps, headlights, beacons). */
    public static final String GLOW_VERT =
            "attribute vec3 a_position;\n"
            + "attribute vec4 a_color;\n"
            + "attribute vec2 a_corner;\n"
            + "uniform mat4 u_projView;\n"
            + "uniform vec3 u_camRight;\n"
            + "uniform vec3 u_camUp;\n"
            + "varying vec4 v_color;\n"
            + "varying vec2 v_corner;\n"
            + "void main() {\n"
            + "  float size = a_color.a;\n"
            + "  vec3 wp = a_position + (u_camRight * a_corner.x + u_camUp * a_corner.y) * size;\n"
            + "  v_color = a_color; v_corner = a_corner;\n"
            + "  gl_Position = u_projView * vec4(wp, 1.0);\n"
            + "}\n";

    public static final String GLOW_FRAG =
            "#ifdef GL_ES\nprecision mediump float;\n#endif\n"
            + "uniform vec3 u_fogColor;\n"
            + "uniform float u_fogStart;\n"
            + "uniform float u_fogEnd;\n"
            + "uniform vec3 u_camPos;\n"
            + "varying vec4 v_color;\n"
            + "varying vec2 v_corner;\n"
            + "void main() {\n"
            + "  float d = length(v_corner);\n"
            + "  float a = clamp(1.0 - d, 0.0, 1.0);\n"
            + "  a = a * a;\n"
            + "  gl_FragColor = vec4(v_color.rgb * a, a);\n"
            + "}\n";

    /** Ground-projected soft shadow cards. */
    public static final String SHADOW_VERT =
            "attribute vec3 a_position;\n"
            + "attribute vec2 a_texCoord0;\n"
            + "uniform mat4 u_projView;\n"
            + "varying vec2 v_uv;\n"
            + "void main() { v_uv = a_texCoord0; gl_Position = u_projView * vec4(a_position, 1.0); }\n";

    public static final String SHADOW_FRAG =
            "#ifdef GL_ES\nprecision mediump float;\n#endif\n"
            + "uniform float u_alpha;\n"
            + "varying vec2 v_uv;\n"
            + "void main() {\n"
            + "  vec2 d = v_uv - vec2(0.5);\n"
            + "  float a = clamp(1.0 - length(d) * 2.0, 0.0, 1.0);\n"
            + "  gl_FragColor = vec4(0.0, 0.0, 0.0, a * a * u_alpha);\n"
            + "}\n";

    private Shaders() {
    }
}
